-- One visit / app session, with device and acquisition details.

CREATE TABLE sessions (
    id            uuid PRIMARY KEY,                 -- generated by the SDK
    project_id    uuid NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    person_id     uuid REFERENCES persons (id) ON DELETE SET NULL,
    started_at    timestamptz NOT NULL,
    ended_at      timestamptz,
    event_count   int NOT NULL DEFAULT 0,
    entry_path    text,
    exit_path     text,
    referrer      text,
    utm_source    text,
    utm_medium    text,
    utm_campaign  text,
    device_type   text,
    os            text,
    browser       text,
    app_version   text,
    country       char(2)
);
CREATE INDEX ix_sessions_project_started ON sessions (project_id, started_at DESC);
CREATE INDEX ix_sessions_person_id ON sessions (person_id);

