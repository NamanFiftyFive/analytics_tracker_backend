"""Models for event ingestion: what SDKs send to POST /ingest/batch and what they get back."""

import json
from datetime import UTC, datetime
from typing import Any, Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator

MAX_EVENTS_PER_BATCH = 100
MAX_PROPERTIES_BYTES = 16_000


class IngestContext(BaseModel):
    """Device details sent once per batch; applied to every event in it."""

    platform: str | None = Field(default=None, max_length=40, examples=["flutter"])
    os: str | None = Field(default=None, max_length=60, examples=["Android 14"])
    browser: str | None = Field(default=None, max_length=60, examples=[None])
    device_type: Literal["mobile", "tablet", "desktop", "tv", "other"] | None = None
    app_version: str | None = Field(default=None, max_length=40, examples=["2.3.1"])
    country: str | None = Field(default=None, pattern=r"^[A-Za-z]{2}$", examples=["IN"])

    @field_validator("country")
    @classmethod
    def uppercase_country(cls, value: str | None) -> str | None:
        return value.upper() if value else value


class IngestEvent(BaseModel):
    """One event. Validated separately for each item in `events`, so one bad event doesn't
    reject the batch. Unknown fields are ignored (newer SDKs may send more)."""

    model_config = ConfigDict(extra="ignore")

    id: UUID = Field(description="Generated by the SDK; the same id sent twice is stored once")
    event: str = Field(min_length=1, max_length=200, examples=["test_drive_booked"])
    distinct_id: str = Field(min_length=1, max_length=200, description="Anonymous id or the app's user id")
    session_id: UUID | None = None
    timestamp: datetime = Field(description="When it happened on the device (ISO 8601; UTC if no offset)")
    path: str | None = Field(default=None, max_length=2000, description="Web: page path")
    screen_name: str | None = Field(default=None, max_length=200, description="App: screen name")
    referrer: str | None = Field(default=None, max_length=2000)
    utm_source: str | None = Field(default=None, max_length=200)
    utm_medium: str | None = Field(default=None, max_length=200)
    utm_campaign: str | None = Field(default=None, max_length=200)
    properties: dict[str, Any] = Field(default_factory=dict)

    @field_validator("timestamp")
    @classmethod
    def assume_utc(cls, value: datetime) -> datetime:
        return value.replace(tzinfo=UTC) if value.tzinfo is None else value.astimezone(UTC)

    @field_validator("properties")
    @classmethod
    def limit_size(cls, value: dict[str, Any]) -> dict[str, Any]:
        if len(json.dumps(value, default=str)) > MAX_PROPERTIES_BYTES:
            raise ValueError(f"properties are larger than {MAX_PROPERTIES_BYTES} bytes")
        return value


class IngestBatch(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "context": {"platform": "flutter", "os": "Android 14", "device_type": "mobile",
                                "app_version": "2.3.1", "country": "IN"},
                    "events": [
                        {"id": "5b1e2c3d-0000-4000-8000-000000000001", "event": "$screen",
                         "distinct_id": "anon-7f3a", "session_id": "9ab30000-0000-4000-8000-000000000001",
                         "timestamp": "2026-10-20T10:15:00Z", "screen_name": "CarDetail",
                         "properties": {"model": "Nexon EV"}},
                        {"id": "5b1e2c3d-0000-4000-8000-000000000002", "event": "test_drive_booked",
                         "distinct_id": "anon-7f3a", "session_id": "9ab30000-0000-4000-8000-000000000001",
                         "timestamp": "2026-10-20T10:16:30Z", "screen_name": "BookTestDrive",
                         "properties": {"model": "Nexon EV", "showroom": "Baner"}},
                    ],
                }
            ]
        }
    )

    api_key: str | None = Field(
        default=None, description="Only for browsers using sendBeacon (can't set headers); otherwise use X-API-Key"
    )
    context: IngestContext = Field(default_factory=IngestContext)
    events: list[dict[str, Any]] = Field(
        min_length=1,
        max_length=MAX_EVENTS_PER_BATCH,
        description="Each item: id, event, distinct_id, timestamp, and optional session_id, path, "
        "screen_name, referrer, utm_source, utm_medium, utm_campaign, properties",
    )


class RejectedEvent(BaseModel):
    index: int = Field(description="Position of the event in the request's `events` list")
    error: str


class IngestResult(BaseModel):
    accepted: int = Field(description="Events stored by this request")
    duplicates: int = Field(description="Valid events already stored earlier (same id), skipped")
    rejected: list[RejectedEvent]
