#!/usr/bin/env python3
"""Guardrails for AI coding agents (Claude Code hooks) in this project.

Called from .claude/settings.json as:  python3 <this file> pre|post|stop
  pre   PreToolUse:  blocks edits to protected files and dangerous shell commands.
  post  PostToolUse: quick check of the edited file; remembers that code changed.
  stop  Stop:        if code changed, runs the project's checks before the agent finishes.

A block is exit code 2 with the reason on stderr: the agent sees why and must find another
way (or ask you). The same file is used by backend/, analytics_tracker/ and
event_tracker_analytics/; it finds its project from its own location (<project>/.claude/hooks/).
"""

import ast
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # the project this copy belongs to
DIRTY = ROOT / ".claude" / ".dirty"           # "code changed since the last checks" marker
IS_BACKEND = (ROOT / "migrations").is_dir() and (ROOT / "app").is_dir()
IS_FLUTTER = (ROOT / "pubspec.yaml").is_file()

# ── Files the agent must not edit ────────────────────────────────────────────

SECRET_NAMES = re.compile(
    r"^(\.env(\..+)?|.*\.(pem|key|p12|pfx|jks|keystore)|key\.properties|id_rsa.*|id_ed25519.*"
    r"|credentials.*\.json|service[-_]account.*\.json)$",
    re.IGNORECASE,
)
SECRET_EXAMPLES = re.compile(r"^\.env\.(example|sample|template)$", re.IGNORECASE)


def applied_migrations() -> set[str]:
    """Versions dbmate has applied, from the schema snapshot it writes after every migration."""
    schema = ROOT / "schema.sql"
    return set(re.findall(r"\('(\d{14})'\)", schema.read_text())) if schema.is_file() else set()


def protected_reason(path: Path) -> str | None:
    """Why the agent may not write this file, or None if it may."""
    name = path.name
    if SECRET_NAMES.match(name) and not SECRET_EXAMPLES.match(name):
        return f"{name} holds secrets. Change it yourself; the agent may only edit .env.example."

    try:
        rel = path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return None  # another project: its own copy of this file decides

    if rel in (".claude/settings.json", ".claude/settings.local.json") or rel.startswith(".claude/hooks/"):
        return "Agent guardrails (.claude/settings*.json, .claude/hooks/) are changed by people only."
    if IS_BACKEND:
        if rel == "schema.sql":
            return "schema.sql is generated by dbmate. Change the schema with a new migration."
        match = re.match(r"migrations/(\d{14})_.*\.sql$", rel)
        if match and match.group(1) in applied_migrations():
            return f"{rel} is already applied. Never edit applied migrations: run `dbmate new <name>` instead."
        if rel.startswith((".venv/", "venv/")):
            return "Installed packages (.venv) are not edited by hand."
    if IS_FLUTTER:
        if rel.startswith("lib/l10n/generated/"):
            return "Generated translations: edit lib/l10n/app_*.arb and run `fvm flutter gen-l10n`."
        if rel == "pubspec.lock":
            return "pubspec.lock is written by `fvm flutter pub get`; change pubspec.yaml instead."
        if rel.startswith(("build/", ".dart_tool/")):
            return "Build output is generated; don't edit it."
    return None


# ── Shell commands ───────────────────────────────────────────────────────────

ENV_FILE = r"\.env(?!\.(example|sample|template))\b"  # .env but not .env.example

BLOCKED_COMMANDS = [
    (r"\brm\s+(-\w*r\w*f|-\w*f\w*r|(-r|--recursive)\s+(-f|--force)|(-f|--force)\s+(-r|--recursive))",
     "Recursive force delete (rm -rf) is blocked. Delete specific files, or ask the user."),
    (r"\bgit\s+push\b.*(\s-f\b|--force)", "Force-push rewrites shared history; it is blocked."),
    (r"\bgit\s+reset\s+--hard|\bgit\s+clean\s+-\w*f|\bgit\s+checkout\s+--\s+\.|\bgit\s+restore\s+\.",
     "Discarding uncommitted work is blocked. Ask the user."),
    (r"--no-verify\b", "Skipping git hooks (--no-verify) is blocked."),
    (r"(?i)\b(drop\s+(table|database|schema|owned)|truncate\s+(table\s+)?\w)",
     "Destructive SQL is blocked. Schema changes go through a new dbmate migration."),
    (r"\bdropdb\b|\bdbmate\s+drop\b", "Dropping a database is blocked."),
    (r"\b(curl|wget)\b[^|]*\|\s*(sudo\s+)?(sh|bash|zsh|python3?)\b", "Piping a download into a shell is blocked."),
    (r"(^|[;&|]\s*)sudo\b", "sudo is blocked."),
    (r"\bchmod\s+(-R\s+)?0?777\b", "World-writable permissions (chmod 777) are blocked."),
    (r"--dangerously-skip-permissions|bypassPermissions", "Bypassing permission checks is blocked."),
    (rf"\b(cat|less|more|head|tail|bat|nl|strings|grep|rg|awk|sed|cut|xxd|od|source)\b[^;&|]*{ENV_FILE}"
     rf"|(^|[;&|]\s*)\.\s+\S*{ENV_FILE}",
     "Reading .env would put secrets in the conversation. Use .env.example to see the keys."),
]

# Shell writes into protected files (the Edit/Write check can't see these).
SHELL_WRITE = r"(>|\btee\b|\bsed\s+-i|\bperl\s+-\w*i|\bmv\b|\bcp\b|\btruncate\b|\brm\b)"
PROTECTED_IN_SHELL = (
    rf"{ENV_FILE}|\.claude/(settings|hooks)|\bschema\.sql\b|l10n/generated/|\bpubspec\.lock\b"
    r"|\bmigrations/\d{14}_"
)

ASK_COMMANDS = [
    (r"\bgit\s+push\b", "Pushing publishes code; confirm first."),
    (r"\bdbmate\s+rollback\b", "Rollback undoes an applied migration and can delete data."),
    (r"\bdocker\s+(volume\s+rm|volume\s+prune|system\s+prune|compose\s+down\b.*(-v\b|--volumes))",
     "This deletes Docker data volumes (the Docker database)."),
    (r"\b(pip3?|python3?\s+-m\s+pip|uv\s+pip)\s+(install|uninstall)\b|\b(flutter|dart)\s+pub\s+(add|remove|upgrade)\b"
     r"|\bnpm\s+(install|i|add)\s+\S",
     "Adding or changing dependencies: a person should check the package first."),
]


def check_command(command: str) -> tuple[str, str] | None:
    """('block' | 'ask', reason) for a risky command, else None."""
    for pattern, reason in BLOCKED_COMMANDS:
        if re.search(pattern, command):
            return "block", reason
    if re.search(SHELL_WRITE, command) and re.search(PROTECTED_IN_SHELL, command):
        if not re.match(r"^\s*dbmate\b", command):  # dbmate itself rewrites schema.sql
            return "block", "This command would change a protected file (secrets, guardrails, generated files or migrations)."
    for pattern, reason in ASK_COMMANDS:
        if re.search(pattern, command):
            return "ask", reason
    return None


# ── Hook entry points ────────────────────────────────────────────────────────

def file_of(tool_input: dict) -> Path | None:
    raw = tool_input.get("file_path") or tool_input.get("notebook_path")
    return Path(raw) if raw else None


def pre(event: dict) -> int:
    tool, tool_input = event.get("tool_name", ""), event.get("tool_input", {})
    if tool in ("Edit", "Write", "MultiEdit", "NotebookEdit"):
        path = file_of(tool_input)
        reason = path and protected_reason(path)
        if reason:
            print(f"Blocked by project guardrail: {reason}", file=sys.stderr)
            return 2
    elif tool == "Bash":
        verdict = check_command(tool_input.get("command", ""))
        if verdict and verdict[0] == "block":
            print(f"Blocked by project guardrail: {verdict[1]}", file=sys.stderr)
            return 2
        if verdict:
            print(json.dumps({"hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "ask",
                "permissionDecisionReason": f"Project guardrail: {verdict[1]}",
            }}))
    return 0


def post(event: dict) -> int:
    """Quick feedback on the file just edited; never blocks."""
    path = file_of(event.get("tool_input", {}))
    if path is None:
        return 0
    try:
        path.resolve().relative_to(ROOT)
    except ValueError:
        return 0
    if path.suffix in (".py", ".dart", ".sql", ".arb", ".yaml"):
        DIRTY.touch()

    problem = None
    if path.suffix == ".py" and path.is_file():
        try:
            ast.parse(path.read_text(), filename=str(path))
        except SyntaxError as error:
            problem = f"Python syntax error in {path.name}:{error.lineno}: {error.msg}"
    elif path.suffix == ".dart" and path.is_file() and IS_FLUTTER:
        result = run(["fvm", "dart", "analyze", str(path)], timeout=60)
        if result is not None and "No issues found" not in result.stdout:
            problem = f"dart analyze {path.name}:\n" + tail(result.stdout)
    if problem:
        print(json.dumps({"hookSpecificOutput": {"hookEventName": "PostToolUse", "additionalContext": problem}}))
    return 0


def stop(event: dict) -> int:
    """Before the agent finishes: if code changed, the project's checks must pass."""
    if not DIRTY.exists():
        return 0
    if IS_BACKEND:
        checks = [[str(ROOT / ".venv/bin/pytest"), "-q", "-x", "-p", "no:cacheprovider"]]
    elif IS_FLUTTER:
        checks = [["fvm", "flutter", "analyze"], ["fvm", "flutter", "test"]]
    else:
        return 0

    for command in checks:
        result = run(command, timeout=280)
        if result is None or result.returncode != 0:
            output = tail(result.stdout + result.stderr) if result else "(could not run)"
            message = f"`{' '.join(command[-2:])}` failed in {ROOT.name}:\n{output}"
            if event.get("stop_hook_active"):
                # Already asked once this turn: report it instead of looping.
                print(json.dumps({"systemMessage": f"Checks still failing in {ROOT.name}; see the last output."}))
                return 0
            print(json.dumps({"decision": "block", "reason": message + "\nFix this before finishing."}))
            return 0
    DIRTY.unlink(missing_ok=True)
    return 0


def run(command: list[str], timeout: int) -> subprocess.CompletedProcess | None:
    try:
        return subprocess.run(command, cwd=ROOT, capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired):
        return None


def tail(text: str, lines: int = 30) -> str:
    return "\n".join(text.strip().splitlines()[-lines:])


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    try:
        payload = json.load(sys.stdin)
    except json.JSONDecodeError:
        payload = {}
    handler = {"pre": pre, "post": post, "stop": stop}.get(mode)
    sys.exit(handler(payload) if handler else 0)
